import pandas as pd

df = pd.read_csv("train.csv")

# базовая информация и проверка на null и повторки

print(df.shape)
print(df.columns)
print(df.isnull().sum())
print(df.duplicated().sum())

# в датасете эти колонки являются форматом object, поэтому меняем их на формат дд/мм/гггг

df["Order Date"] = pd.to_datetime(df["Order Date"], format="%d/%m/%Y")
df["Ship Date"] = pd.to_datetime(df["Ship Date"], format="%d/%m/%Y")

print(df.dtypes)

# смотрим диапазон дат

print(df["Order Date"].min())
print(df["Order Date"].max())

# топ 10 заказов по сумме продаж

print(df.sort_values("Sales", ascending=False).head(10))

# считаем общие продажи по каждой категории

print(df.groupby("Category")["Sales"].sum())

# Technology лидирует по продажам (827,5 тыс.), но отрыв от Office Supplies (705,4 тыс.)(это наименьшая категория) составляет около 17%. Значимого перекоса нет, так как выручка распределена между тремя категориями относительно равномерно, бизнес не зависит критично только от одной товарной группы

# выбираем год как отдельную колонку

df["Order Year"] = df["Order Date"].dt.year

# анализ продаж за 2018 год

print(df[df["Order Year"] == 2018].head())
print(df[df["Order Year"] == 2018].groupby("Sub-Category")["Sales"].sum().sort_values(ascending=False))

# Внутри категорий продажи распределены крайне неравномерно: Phones (104,7 тыс.) - лидер, но Fasteners (0,9 тыс.) отстаёт от него более чем в 120 раз. При этом три подкатегории (Phones, Chairs, Binders) формируют заметно больше выручки, чем нижние 8-9 позиций списка вместе взятые. Это показывает, что за ровной картиной на уровне Category скрывается сильная концентрация продаж в узком наборе товаров: именно они определяют выручку года, а не категория в целом
# продажи по регионам

print(df.groupby("Region")["Sales"].agg(["sum", "mean", "count"]))
# West лидирует и по общей выручке (710,2 тыс.), и по количеству заказов (3140), то есть выручка растёт здесь за счёт объёма, а не за счёт дорогих заказов: средний чек тут ниже (226), чем в East и South. При этом South, имея наименьшее число заказов (1598) среди всех регионов кроме Central, показывает самый высокий средний чек (243,5) - покупки здесь реже, но крупнее. Central отстаёт по всем трём метрикам сразу (наименьшая выручка, наименьшее число заказов, второй по величине средний чек) - это регион с наименьшим потенциалом или наименее охваченный
# базовая информация

print(df.describe())

# считаем время доставки в днях и среднее время доставки по каждому виду транспортировки

df['Delivery Days'] = (df['Ship Date'] - df['Order Date']).dt.days
print(df[['Order Date', 'Ship Date', 'Delivery Days']].head())
print(df.groupby('Ship Mode')['Delivery Days'].mean())

# Среднее время доставки чётко соответствует уровню сервиса: Same Day - практически мгновенно (0,04 дня), First Class - около 2,2 дней, Second Class - 3,2 дня, Standard Class — 5 дней. Разница между самым быстрым платным вариантом (First Class) и стандартной доставкой - почти в 2,3 раза. Это подтверждает, что типы доставки в данных реально различаются по скорости (не просто разные названия для одного и того же процесса), и Standard Class (самый медленный вариант) вероятно, выбирается основной массой клиентов, если судить по тому, что именно на него чаще всего смотрят как на базовый tier
# топ 10 покупателей по их сумме покупок

print(df.groupby('Customer Name')['Sales'].sum().sort_values(ascending=False).head(10))

# сводная таблица продаж по категории и региону

pivot = pd.pivot_table(df, values='Sales', index='Category', columns='Region', aggfunc='sum')
print(pivot)
pivot.to_csv('category_region.csv')
